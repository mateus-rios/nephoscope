export const kitCollections: readonly KitCollection[] = [...baseCollections, ...computeCollections, ...dataCollections];

export function findKitCollection(key: string): KitCollection | undefined {
  return kitCollections.find((c) => c.key === key);
}

/** Collections shown as tabs of a product page: those that are nobody's child. */
export function kitTopLevel(product: string): KitCollection[] {
  const children = new Set(kitCollections.flatMap((c) => c.children ?? []));
  return kitCollections.filter((c) => c.product === product && !children.has(c.key));
}
