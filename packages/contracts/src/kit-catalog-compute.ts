/**
 * Compute Engine, VPC network and GKE through the resource kit (SPEC-0008 D-07, D-08, D-11).
 * Compute paths are self links after the project, such as `zones/{z}/instances/{i}`.
 */

const NAME = '^[a-z]([-a-z0-9]{0,61}[a-z0-9])?$';
const CIDR = String.raw`^(\d{1,3}\.){3}\d{1,3}/\d{1,2}$`;
const CIDR_LIST = String.raw`^(\d{1,3}\.){3}\d{1,3}/\d{1,2}(\s*,\s*(\d{1,3}\.){3}\d{1,3}/\d{1,2})*$`;
const TAGS = String.raw`^[a-z]([-a-z0-9]{0,61}[a-z0-9])?(\s*,\s*[a-z]([-a-z0-9]{0,61}[a-z0-9])?)*$`;
const LABELS = String.raw`^[a-z][a-z0-9_-]{0,62}=[a-z0-9_-]{0,63}(\s*,\s*[a-z][a-z0-9_-]{0,62}=[a-z0-9_-]{0,63})*$`;
const PROTO = String.raw`(tcp|udp|icmp|esp|ah|sctp|ipip|\d{1,3})(:\d{1,5}(-\d{1,5})?)?`;
const RULES = `^(all|${PROTO}(\\s*,\\s*${PROTO})*)$`;
const REGION = '^[a-z]+-[a-z]+[0-9]+$';

const zonal = (collection: string) => `^zones/${S}/${collection}/${S}$`;
const scoped = (collection: string) => `^(zones|regions)/${S}/${collection}/${S}$`;
const globalOrRegional = (collection: string) => `^(global|regions/${S})/${collection}/${S}$`;
const global = (collection: string) => `^global/${collection}/${S}$`;

const nameField = (label = 'Name'): KitField => ({ id: 'id', label, kind: 'text', required: true, pattern: NAME });
const networkField: KitField = { id: 'network', label: 'Network', kind: 'text', required: true, pattern: NAME, initial: 'default' };

const instanceStatus = ready('status', {
  running: ['STAGING', 'SUSPENDING'],
  paused: ['TERMINATED'],
});

const simple = (id: string, label: string, consequence: string, statusIn: string[], verb: string): KitAction => ({
  id,
  label,
  consequence,
  when: { path: 'status', in: statusIn },
  gcloud: `gcloud compute instances ${verb} {id} --zone={location} --project={project}`,
});

